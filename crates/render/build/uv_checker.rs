//! The UV checker's GPU-ready textures, baked at build time.
//!
//! What an artist edits is the two checker PNGs in `assets/textures/`. What the
//! viewer ships is each one's full mip chain, BC7-encoded and then deflated, which
//! `src/scene/checker.rs` inflates and uploads as it stands: no PNG decode and no mip
//! generation at run time, and a quarter of the VRAM an RGBA8 chain takes.
//!
//! Measured on the two 2048² checkers (release): the run-time path this replaced
//! spent ~21 ms per checker, 6 ms decoding the PNG and 15 ms building the chain;
//! this one spends 2-3 ms inflating. The chain is 5.6 MB of BC7 against 22 MB of
//! RGBA8, and deflates to 150-180 KB in the binary, since BC7's blocks repeat as
//! often as the checker's cells do - the same size, near enough, as deflating the
//! RGBA8 chain, which is why it is not stored that way. The encode is BC7's slowest,
//! highest-quality profile: it reproduces the chain at 61-67 dB PSNR, and costs ~11 s
//! of encoding per checker, spread over every core and skipped altogether when
//! nothing it reads has changed ([`STAMP`]).
//!
//! The chain comes from the run-time's own `src/rhi/mips.rs`, compiled into this
//! script by path, so it is the chain the viewer used to build for itself: a 2×2 box
//! averaged in linear light, which is what a material map gets too.

use std::borrow::Cow;
use std::num::NonZero;
use std::path::Path;

use intel_tex_2::{RgbaSurface, bc7};

use crate::mips;

/// One checker: the PNG it is baked from, and the constant `src/scene/checker.rs`
/// names it by.
struct Checker {
    png: &'static str,
    constant: &'static str,
}

const CHECKERS: [Checker; 2] = [
    Checker {
        png: "T_UV_Checker_BW.png",
        constant: "GREYSCALE",
    },
    Checker {
        png: "T_UV_Checker_CLR.png",
        constant: "COLOR",
    },
];

/// The Rust file the checkers are described in, under `OUT_DIR`, which
/// `src/scene/checker.rs` `include!`s.
const GENERATED: &str = "uv_checker.rs";

/// The digest of everything the last bake read, under `OUT_DIR`.
///
/// This script also reruns for every shader edit, and the encode is the slowest
/// thing in it, so it is skipped while the PNGs and the code that bakes them are
/// the ones the outputs were made from. The code is in the digest as well as the art
/// (`include_bytes!` of this file and of `mips.rs`), because a change to the bake
/// recompiles this script, and a recompiled script reruns with the old outputs still
/// lying in `OUT_DIR`.
const STAMP: &str = "uv_checker.stamp";

/// miniz's highest level ("uber"). The encode runs once per change, so the slowest
/// setting costs nothing that matters.
const DEFLATE_LEVEL: u8 = 10;

/// Bytes per BC7 block (4×4 texels).
const BLOCK_BYTES: usize = 16;

/// Bake both checkers into `out_dir`, unless what is there was baked from the same
/// inputs.
pub(crate) fn bake(crate_dir: &Path, out_dir: &Path) {
    let textures = crate_dir.join("../../assets/textures");
    let pngs: Vec<Vec<u8>> = CHECKERS
        .iter()
        .map(|checker| {
            let path = textures.join(checker.png);
            println!("cargo:rerun-if-changed={}", path.display());
            std::fs::read(&path)
                .unwrap_or_else(|err| panic!("could not read {}: {err}", path.display()))
        })
        .collect();

    let stamp = digest(&pngs);
    let stamp_path = out_dir.join(STAMP);
    let outputs_present = out_dir.join(GENERATED).is_file()
        && CHECKERS
            .iter()
            .all(|checker| out_dir.join(payload_name(checker)).is_file());
    if outputs_present && std::fs::read_to_string(&stamp_path).is_ok_and(|done| done == stamp) {
        return;
    }

    let mut generated =
        String::from("// Generated by crates/render/build/uv_checker.rs. Do not edit.\n");
    for (checker, png) in CHECKERS.iter().zip(&pngs) {
        let baked = bake_one(checker.png, png);
        let payload = payload_name(checker);
        write(&out_dir.join(&payload), &baked.deflated);
        generated.push_str(&format!(
            "\n/// `{png}`: {width}x{height}, {levels} levels, {len} bytes of BC7.\n\
             const {constant}: BakedChecker = BakedChecker {{\n    \
                 width: {width},\n    \
                 height: {height},\n    \
                 levels: {levels},\n    \
                 len: {len},\n    \
                 deflated: include_bytes!(concat!(env!(\"OUT_DIR\"), \"/{payload}\")),\n\
             }};\n",
            png = checker.png,
            constant = checker.constant,
            width = baked.width,
            height = baked.height,
            levels = baked.levels,
            len = baked.len,
        ));
    }
    write(&out_dir.join(GENERATED), generated.as_bytes());
    // Last, so a bake interrupted part-way is redone rather than trusted.
    write(&stamp_path, stamp.as_bytes());
}

/// What one checker bakes to.
struct Baked {
    width: u32,
    height: u32,
    levels: u32,
    /// The BC7 chain's length before deflating, which the run-time checks the
    /// inflated payload against.
    len: usize,
    deflated: Vec<u8>,
}

/// Decode `png`, build its sRGB mip chain, BC7-encode every level and deflate the
/// lot. `name` is for the panic messages.
fn bake_one(name: &str, png: &[u8]) -> Baked {
    let rgba = image::load_from_memory_with_format(png, image::ImageFormat::Png)
        .unwrap_or_else(|err| panic!("{name} is not a readable PNG: {err}"))
        .to_rgba8();
    let (width, height) = rgba.dimensions();
    assert!(
        width.is_multiple_of(4) && height.is_multiple_of(4),
        "{name} is {width}x{height}; a BC7 texture's top level has to be whole 4x4 blocks"
    );
    let base = rgba.as_raw().as_slice();
    // The opaque profile spends nothing on alpha; a checker with transparency in it
    // would need the alpha one, so the art decides rather than an assumption here.
    let settings = if base
        .as_chunks::<4>()
        .0
        .iter()
        .all(|texel| texel[3] == u8::MAX)
    {
        bc7::opaque_slow_settings()
    } else {
        bc7::alpha_slow_settings()
    };

    let chain = mips::levels_below_base(base, width, height, true);
    let mut blocks = Vec::new();
    let (mut level_width, mut level_height) = (width, height);
    for level in std::iter::once(base).chain(chain.iter().map(Vec::as_slice)) {
        blocks.extend(encode_level(&settings, level, level_width, level_height));
        (level_width, level_height) = ((level_width / 2).max(1), (level_height / 2).max(1));
    }
    Baked {
        width,
        height,
        levels: chain.len() as u32 + 1,
        len: blocks.len(),
        deflated: miniz_oxide::deflate::compress_to_vec(&blocks, DEFLATE_LEVEL),
    }
}

/// BC7-encode one level, in strips of block rows across every core. Each block is
/// encoded on its own, so the split changes nothing in the output.
fn encode_level(settings: &bc7::EncodeSettings, texels: &[u8], width: u32, height: u32) -> Vec<u8> {
    let (texels, width, height) = pad_to_blocks(texels, width, height);
    let block_rows = (height / 4) as usize;
    let row_bytes = (width / 4) as usize * BLOCK_BYTES;
    // Four rows of texels make one row of blocks.
    let texel_row_bytes = width as usize * 4 * 4;
    let threads = std::thread::available_parallelism()
        .map_or(1, NonZero::get)
        .min(block_rows);
    let rows_per_strip = block_rows.div_ceil(threads);

    let mut blocks = vec![0u8; block_rows * row_bytes];
    std::thread::scope(|scope| {
        for (strip, out) in blocks.chunks_mut(rows_per_strip * row_bytes).enumerate() {
            let first = strip * rows_per_strip;
            let rows = out.len() / row_bytes;
            let data = &texels[first * texel_row_bytes..(first + rows) * texel_row_bytes];
            scope.spawn(move || {
                let surface = RgbaSurface {
                    width,
                    height: rows as u32 * 4,
                    stride: width * 4,
                    data,
                };
                bc7::compress_blocks_into(settings, &surface, out);
            });
        }
    });
    blocks
}

/// `texels` grown to whole 4×4 blocks by repeating the last row and column. Only the
/// 2×2 and 1×1 levels need it, and the GPU never samples the padding: it is there so
/// the encoder has a full block to fit, and repeating the edge keeps that block's
/// endpoints the level's own colours.
fn pad_to_blocks(texels: &[u8], width: u32, height: u32) -> (Cow<'_, [u8]>, u32, u32) {
    let (padded_width, padded_height) = (width.next_multiple_of(4), height.next_multiple_of(4));
    if (padded_width, padded_height) == (width, height) {
        return (Cow::Borrowed(texels), width, height);
    }
    let mut padded = Vec::with_capacity(padded_width as usize * padded_height as usize * 4);
    for y in 0..padded_height {
        let row = y.min(height - 1) as usize * width as usize;
        for x in 0..padded_width {
            let at = (row + x.min(width - 1) as usize) * 4;
            padded.extend_from_slice(&texels[at..at + 4]);
        }
    }
    (Cow::Owned(padded), padded_width, padded_height)
}

/// The deflated chain's file name under `OUT_DIR`.
fn payload_name(checker: &Checker) -> String {
    let stem = checker.png.trim_end_matches(".png");
    format!("{stem}.bc7.deflate")
}

/// SHA-256, as hex, over the PNGs and the code that bakes them (see [`STAMP`]).
fn digest(pngs: &[Vec<u8>]) -> String {
    use sha2::{Digest, Sha256};

    let mut hasher = Sha256::new();
    for png in pngs {
        hasher.update(png);
    }
    hasher.update(include_bytes!("uv_checker.rs"));
    hasher.update(include_bytes!("../src/rhi/mips.rs"));
    hasher
        .finalize()
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect()
}

fn write(path: &Path, bytes: &[u8]) {
    std::fs::write(path, bytes)
        .unwrap_or_else(|err| panic!("could not write {}: {err}", path.display()));
}
